export type MiscKey = keyof typeof miscStrings;

/**
 * Get a translation for a given key, using the current locale.
 */
export function miscT(key: MiscKey): string {
  const locale = getLocale();
  const entry = miscStrings[key];
  if (!entry) return key;
  return entry[locale] || entry.uk;
}

/**
 * React hook variant — call inside components.
 * Returns a `t` function and the current locale.
 */
export function useMiscT() {
  const locale = getLocale();
  const t = (key: MiscKey): string => {
    const entry = miscStrings[key];
    if (!entry) return key;
    return entry[locale] || entry.uk;
  };
  return { t, locale };
}
