  const [copied, setCopied] = useState(false);
  const [filter, setFilter] = useState<'all' | 'tech' | 'legal'>('all');

  // Auto-open article from ?article= query param (used after login redirect)
  useEffect(() => {
    const articleId = searchParams.get('article');
    if (articleId && !selectedArticle) {
      const found = articles.find((a) => a.id === articleId);
      if (found) {
        setSelectedArticle(found);
        // Clean the query param from URL
        searchParams.delete('article');
        setSearchParams(searchParams, { replace: true });
      }
    }
  }, [searchParams]);

  // Comments state
  const [comments, setComments] = useState<BlogComment[]>([]);
  const [commentText, setCommentText] = useState('');
  const [commentsLoading, setCommentsLoading] = useState(false);
  const [commentSubmitting, setCommentSubmitting] = useState(false);

  const loadComments = useCallback(async (articleId: string) => {
    setCommentsLoading(true);
    try {
      const data = await blogService.getComments(articleId);
      setComments(data);
    } catch {
      setComments([]);
    } finally {
      setCommentsLoading(false);
    }
  }, []);

  // Load comments when article is selected
  useEffect(() => {
    if (selectedArticle) {
      loadComments(selectedArticle.id);
      setCommentText('');
    } else {
      setComments([]);
    }
  }, [selectedArticle, loadComments]);

  const handleSubmitComment = async () => {
    if (!selectedArticle || !commentText.trim() || commentSubmitting) return;
    setCommentSubmitting(true);
    try {
      const newComment = await blogService.postComment(selectedArticle.id, commentText.trim());
      setComments(prev => [newComment, ...prev]);
      setCommentText('');
    } catch {
      // handled silently
    } finally {
      setCommentSubmitting(false);
    }
  };

  const handleDeleteComment = async (commentId: number) => {
    try {
      await blogService.deleteComment(commentId);
      setComments(prev => prev.filter(c => c.id !== commentId));
    } catch {
      // handled silently
    }
  };

  const filtered = filter === 'all' ? articles : articles.filter(a => a.category === filter);

  const shareOnLinkedIn = (article: Article) => {
    const text = encodeURIComponent(`${article.punchline}\n\n#LegalTech #AI #LEXai`);
    window.open(`https://www.linkedin.com/sharing/share-offsite/?text=${text}`, '_blank');
  };

  const copyArticle = (article: Article) => {
    const text = `${article.content}\n\n---\n\n${article.tags.map(t => `#${t}`).join(' ')}`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

